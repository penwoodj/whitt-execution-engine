#!/usr/bin/env python3
"""Generate a batch baseline workflow: all PENDING benchmark cases as
sequential 9B steps in ONE run (single model load — converts per-case
load storms into one). Reads results/benchmark/baseline-rea-bNN.json
markers to find pending cases; writes workflows/baseline-batch.yml with
absolute case paths. Regenerate after any partial run: only pending
cases are included, so re-running the batch resumes.

Usage: gen-batch-baseline.py [--out workflows/baseline-batch.yml]
"""

import argparse
import sys
from pathlib import Path

REA = Path(__file__).parent.parent
BENCH = REA / "results" / "benchmark"
CASES = REA / "cases" / "benchmark"

STEP_TEMPLATE = """    step_b{num}:
      generative_entity: "${{models.baseline_model}}"
      prompt: |
        {{{{bookmarks.shell_output.stdout}}}}
      model_overrides: {{ temperature: 0.7, max_tokens: 500 }}
      when:
        before_step_starts:
          - shell:
              command: "python3 {repo}/experiments/reasoning-enhancer/scripts/emit-case.py --case {case} --run-dir __OUTPUT_DIR__ --phase baseline --out __OUTPUT_DIR__/b{num}-prompt.txt; EXIT=$?; echo $EXIT > __OUTPUT_DIR__/b{num}-prompt.exit; exit $EXIT"
              working_dir: "__REPO_ROOT__"
              fail_on_error: true
        after_step_succeeds:
          - save_to:
              - $text_state
              - "__OUTPUT_DIR__/b{num}-answer.txt"
          - shell:
              command: "python3 {repo}/experiments/reasoning-enhancer/scripts/check-answer.py --case {case} --text-file __OUTPUT_DIR__/b{num}-answer.txt --out __OUTPUT_DIR__/b{num}-check.json > __OUTPUT_DIR__/b{num}-check.log 2>&1; EXIT=$?; echo $EXIT > __OUTPUT_DIR__/b{num}-check.exit; exit $EXIT"
              working_dir: "__REPO_ROOT__"
              fail_on_error: false
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(REA / "workflows" / "baseline-batch.yml"))
    args = ap.parse_args()

    pending = []
    for cf in sorted(CASES.glob("case-b*.yml")):
        import yaml
        cid = yaml.safe_load(cf.read_text())["case_id"]
        if not (BENCH / f"baseline-{cid}.json").exists():
            pending.append((cf, cid))

    if not pending:
        print("no pending cases — all baselines complete")
        return 0

    repo = str(REA.parent.parent)
    steps = []
    for cf, cid in pending:
        num = cid.replace("rea-b", "")
        steps.append(STEP_TEMPLATE.format(num=num, case=str(cf.resolve()), repo=repo))

    wf = f"""# Generated by gen-batch-baseline.py — {len(pending)} pending case(s), one 9B load.
# Regenerate to resume: completed cases are omitted.
workflow_id: rea_baseline_batch
name: "REA Benchmark Baseline Batch"
description: "Sequential 9B direct answers for pending benchmark cases; single model load."
version: "1.0.0"
author: "Whitt Execution Engine"
tags: [benchmark, baseline, 9b, batch]
schema_version: "2.0.0"
min_schema_version: "2.0.0"

providers:
  llama_cpp_with_vulkan:
    config: {{ host: localhost, port: 8080 }}

models:
  "baseline_model":
    name: "Qwen3-5-9B-Q4_K_M"
    host: {{ type: llama_cpp_with_vulkan }}
    sampling: {{ temperature: 0.7, max_tokens: 500 }}

workflow_execution_strategy:
  memory: {{ model_lifecycle: {{ unload_unused: false }} }}

agentic_workflow:
  when:
    after_workflow:
      - log:
          to_file_path: "__OUTPUT_DIR__/last-run.log"
          event_fields: [workflow_id, total_steps, succeeded, failed]
          level: info

  steps:
{"".join(steps)}
    step_99_finalize:
      generative_entity: "${{models.baseline_model}}"
      prompt: "OK."
      model_overrides: {{ temperature: 0.0, max_tokens: 3 }}
      when:
        before_step_starts:
          - shell:
              command: "true"
              working_dir: "__REPO_ROOT__"
              fail_on_error: true
          - skip_step: true
        after_step_succeeds:
          - log:
              to_file_path: "__OUTPUT_DIR__/summary.log"
              event_fields: [workflow_id, total_steps]
              level: info
"""
    Path(args.out).write_text(wf)
    print(f"generated {args.out}: {len(pending)} steps for "
          + ", ".join(cid for _, cid in pending))
    return 0


if __name__ == "__main__":
    sys.exit(main())
